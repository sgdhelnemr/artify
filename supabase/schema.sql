-- ---------- Tables ----------
create table if not exists public.paintings (
  id          bigint generated by default as identity primary key,
  title       text        not null,
  artist      text        not null,
  year        int         not null,
  price       numeric     not null check (price > 0),
  image       text        not null default '',
  description text        not null default '',
  created_by  uuid        default auth.uid() references auth.users(id) on delete set null,
  created_at  timestamptz not null default now()
);

create table if not exists public.comments (
  id          bigint generated by default as identity primary key,
  painting_id bigint      not null references public.paintings(id) on delete cascade,
  user_id     uuid        not null default auth.uid() references auth.users(id) on delete cascade,
  user_email  text,
  text        text        not null check (char_length(text) between 2 and 500),
  created_at  timestamptz not null default now()
);

-- ---------- Row Level Security ----------
alter table public.paintings enable row level security;
alter table public.comments  enable row level security;

-- Paintings: any signed-in user can read and manage the gallery (demo setup).
-- For production, restrict update/delete to: using (created_by = auth.uid())
create policy "paintings_select" on public.paintings for select to authenticated using (true);
create policy "paintings_insert" on public.paintings for insert to authenticated with check (true);
create policy "paintings_update" on public.paintings for update to authenticated using (true) with check (true);
create policy "paintings_delete" on public.paintings for delete to authenticated using (true);

-- Comments: everyone signed-in can read; users can only add/delete their own.
create policy "comments_select" on public.comments for select to authenticated using (true);
create policy "comments_insert" on public.comments for insert to authenticated with check (user_id = auth.uid());
create policy "comments_delete" on public.comments for delete to authenticated using (user_id = auth.uid());

