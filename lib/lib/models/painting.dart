class Painting {
  final int id;
  final String title;
  final String artist;
  final int year;
  final double price;
  final String image; // asset path, network URL, or empty
  final String description;

  const Painting({
    required this.id,
    required this.title,
    required this.artist,
    required this.year,
    required this.price,
    required this.image,
    required this.description,
  });

  factory Painting.fromMap(Map<String, dynamic> m) => Painting(
        id: m['id'] as int,
        title: m['title'] as String,
        artist: (m['artist'] as String?) ?? 'Unknown',
        year: (m['year'] as num?)?.toInt() ?? 0,
        price: (m['price'] as num?)?.toDouble() ?? 0,
        image: (m['image'] as String?) ?? '',
        description: (m['description'] as String?) ?? '',
      );

  /// Used for insert/update (the id is generated by the database).
  Map<String, dynamic> toMap() => {
        'title': title,
        'artist': artist,
        'year': year,
        'price': price,
        'image': image,
        'description': description,
      };
}
